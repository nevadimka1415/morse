using MorseTrainer.Localization;

namespace MorseTrainer.Domain;

/// <summary>Страница «книжки» курса: заголовок и абзацы.</summary>
public sealed record BookPage(string Title, IReadOnlyList<string> Paragraphs);

/// <summary>
/// «Книжка» перед курсом «С нуля до 60 зн/мин» (Windows и телефон): как устроен курс, что такое метод Коха, скорость
/// и паузы, путь по шагам, как заниматься. Список шагов строится из самого курса — если шаги изменятся, текст тоже.
/// </summary>
public static class CourseBook
{
    public static IReadOnlyList<BookPage> Pages(AlphabetMode alphabet)
    {
        var steps = Course.Steps(alphabet);
        // Неразрывный пробел: «К М» не должны разъезжаться по строкам
        var first = string.Join('\u00A0', KochMethod.Pool(Course.AlphabetFor((int)alphabet), KochMethod.MinLevel));
        return new[]
        {
            new BookPage(Texts.T("Как устроен курс"), new[]
            {
                Texts.F("Курс ведёт от нуля до приёма на слух {0} знаков в минуту — это уверенная скорость, с которой уже можно работать в эфире.", Course.TargetSpeed),
                Texts.F("В курсе {0} шагов. Каждый шаг — короткое задание: оно звучит, вы записываете услышанное на бумаге и сверяете с текстом задания.", steps.Count),
                Texts.T("Кнопка шага сама ставит всё нужное: какие знаки, скорость, паузы. Настраивать вручную ничего не придётся."),
                Texts.F("Шаг засчитан, когда в его задании принято {0} % знаков и больше. Чтобы программа это увидела, введите принятое в поле ответа — на шагах курса оно открывается само — и нажмите «Проверить ответ». После зачёта открывается следующий шаг.", Course.PassAccuracy)
            }),
            new BookPage(Texts.T("Метод Коха"), new[]
            {
                Texts.T("Курс построен на методе Коха. Его придумал немецкий психолог Людвиг Кох в 1930-х годах, и с тех пор так учат радиолюбителей по всему миру."),
                Texts.T("Главная идея: знак с первого дня звучит на рабочей скорости. Тогда мозг запоминает его звучание целиком, как короткую мелодию, а не считает точки и тире. Кто учит медленно, привыкает переводить по «таблице в голове» — и потом упирается в потолок: на скорости выше 40–50 знаков в минуту таблица не успевает."),
                Texts.F("Начинаем всего с двух знаков — {0}. Задания состоят только из них. Как только точность держится на {1} %, добавляются новые знаки — по четыре за шаг, пока не пройдёте весь алфавит и цифры.", first, Course.PassAccuracy),
                Texts.T("Порядок знаков выбран так, чтобы каждый новый хорошо отличался на слух от уже знакомых.")
            }),
            new BookPage(Texts.T("Скорость и паузы"), new[]
            {
                Texts.F("Знак всегда звучит на {0} знаков в минуту — с первого шага и до экзамена.", Course.TargetSpeed),
                Texts.T("На первых шагах паузы между знаками и группами растянуты: сам знак быстрый, а время записать есть. Этот приём называют методом Фарнсворта. Дальше паузы постепенно становятся обычными."),
                Texts.T("Последний добавленный знак звучит чаще остальных — так он быстрее запоминается."),
                Texts.T("Перед заданием звучит Ж Ж Ж и пауза: это сигнал «приготовиться». Во время прослушивания над текстом задания видно, какая группа звучит, — на бумаге легко не сбиться.")
            }),
            new BookPage(Texts.T("Путь по шагам"), StepLines(steps)),
            new BookPage(Texts.T("Как заниматься"), new[]
            {
                Texts.T("10–15 минут каждый день дают больше, чем час раз в неделю."),
                Texts.T("Пропустили знак — поставьте точку и слушайте дальше. Не пытайтесь вспомнить: следующий знак уже звучит."),
                Texts.T("Не считайте точки и тире — слушайте ритм целиком. Напевы на карточках «Обучения» помогают запомнить ритм каждого знака."),
                Texts.F("Не торопитесь на следующий шаг: {0} % — знак того, что знаки узнаются уверенно, а не угадываются.", Course.PassAccuracy),
                Texts.F("Готовы? Первый шаг — всего два знака: {0}.", first)
            })
        };
    }

    /// <summary>«1. К М», «2. + Р С У А», … затем шаги со словами и экзамен — как в самом курсе.</summary>
    private static IReadOnlyList<string> StepLines(IReadOnlyList<CourseStep> steps)
    {
        var lines = new List<string>();
        var previous = 0;
        foreach (var step in steps)
        {
            if (step.Content == ContentMode.Koch)
            {
                var added = string.Join(' ', KochMethod.Pool(step.Alphabet, step.KochLevel).Skip(previous));
                lines.Add(previous == 0 ? $"{step.Number}. {added}" : $"{step.Number}. + {added}");
                previous = step.KochLevel;
            }
            else
            {
                lines.Add($"{step.Number}. {step.Title}");
            }
        }

        return lines;
    }
}
