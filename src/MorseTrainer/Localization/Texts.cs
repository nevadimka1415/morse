using System.Globalization;

namespace MorseTrainer.Localization;

public enum AppLanguage
{
    System = 0,
    Russian = 1,
    English = 2
}

/// <summary>
/// Локализация интерфейса. Ключ — русская строка как она написана в XAML и коде,
/// значение — английский перевод. Нет перевода — показывается русский текст.
/// </summary>
public static class Texts
{
    public static AppLanguage Language { get; private set; } = AppLanguage.Russian;

    public static bool IsEnglish { get; private set; }

    /// <summary>Выбор языка: системный (английский для всех, кроме русской локали), русский или английский.</summary>
    public static void Apply(AppLanguage language, string? systemTwoLetterIso = null)
    {
        Language = language;
        IsEnglish = language switch
        {
            AppLanguage.English => true,
            AppLanguage.Russian => false,
            _ => systemTwoLetterIso is not null && !systemTwoLetterIso.Equals("ru", StringComparison.OrdinalIgnoreCase)
        };
    }

    public static string T(string russian)
    {
        return IsEnglish && English.TryGetValue(russian, out var translated) ? translated : russian;
    }

    public static string F(string russian, params object?[] args)
    {
        return string.Format(CultureInfo.CurrentCulture, T(russian), args);
    }

